// Real Chromium interaction with the actual form component. External auth,
// catalog and action are isolated synthetic adapters, never production writes.
import assert from "node:assert/strict";
import { mkdirSync, readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import ts from "typescript";
const require = createRequire(import.meta.url);
const source = readFileSync(new URL("../components/chat/InChatFormCard.tsx", import.meta.url), "utf8");
const compiled = ts.transpileModule(source, { compilerOptions: {
  jsx: ts.JsxEmit.React, module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022
}}).outputText;
const reactPath = join(dirname(require.resolve("react/package.json")), "umd/react.development.js");
const domPath = join(dirname(require.resolve("react-dom/package.json")), "umd/react-dom.development.js");

export async function runFormRegression(browser) {
  const evidence = process.env.QA_EVIDENCE_DIR || "qa-evidence";
  mkdirSync(evidence, {recursive:true});
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, serviceWorkers: "block" });
  try {
    await context.tracing.start({ screenshots: true, snapshots: true, sources: true });
    const page = await context.newPage();
    await page.route("http://localhost:8765/**", route => route.fulfill({ contentType: "text/html", body: '<!doctype html><div id="root"></div>' }));
    await page.goto("http://localhost:8765/");
    await page.addScriptTag({ path: reactPath });
    await page.addScriptTag({ path: domPath });
    await page.evaluate(code => {
      const React = window.React;
      const item = { id: "fixture-catalog", name: "Barangay Clearance", description: "Synthetic catalog", requirements_json: ["Valid ID"] };
      const chain = { select: () => chain, eq: () => chain, limit: () => Promise.resolve({data: [item],error:null}), maybeSingle: () => Promise.resolve({data:null,error:null}) };
      const client = {auth:{getUser:async()=>({data:{user:{id:"fixture-user"}}})},from:()=>chain};
      window.fixtureCalls = [];
      window.fixtureReceipt = false;
      const stub = {
        "react": React,
        "next/link": {default: props => React.createElement("a", props)},
        "lucide-react": new Proxy({}, {get:()=>()=>null}),
        "@/lib/supabase/client": {createClient:()=>client},
        "@/app/(app)/requests/actions": {submitDocumentRequest:async payload=>{
          const f = payload.get("file_Valid ID");
          window.fixtureCalls.push({id:payload.get("clientOperationId"),purpose:payload.get("purpose"),name:f?.name,size:f?.size});
          if (!window.fixtureReceipt) throw new Error("Synthetic network failure");
          return {success:true,reference:"TEST-ONLY-001"};
        }},
        "@/lib/ai/document-forms": {DOCUMENT_FORMS:{clearance:{title:"Barangay Clearance"}},isDocumentFormId:()=>true},
        "@/lib/navigation/nav-badges": {NAV_BADGES_CHANGED:"fixture-badges"},
        "@/lib/request-receipt": {isValidIdRequirement:()=>true},
        "@/lib/verified-resident-evidence": {hasRegistrationIdOnFile:()=>false,isResidencyProofRequirement:()=>false},
      };
      const exports = {};
      new Function("require","exports","React",code)(name=>{
        if (!(name in stub)) throw Error("Unexpected import: "+name);
        return stub[name];
      },exports,React);
      const Root = () => React.createElement(exports.InChatFormCard,{formType:"clearance",title:"Barangay Clearance"});
      ReactDOM.createRoot(document.querySelector("#root")).render(React.createElement(Root));
    },compiled);
    const form = page.getByRole("region",{name:"Interactive Document Application Form"});
    await form.waitFor();
    await form.locator("textarea").fill("Synthetic defense test only");
    // Valid JPEG generated by Chromium; no real ID image.
    const jpeg = Buffer.from(await page.evaluate(() => {
      const c=document.createElement("canvas");c.width=16;c.height=16;
      const ctx=c.getContext("2d");ctx.fillStyle="#fff";ctx.fillRect(0,0,16,16);
      return c.toDataURL("image/jpeg").split(",")[1];
    }),"base64");
    const input = form.locator('input[type="file"]');
    await input.setInputFiles({name:"sample.jpg",mimeType:"image/jpeg",buffer:jpeg});
    await form.getByText("sample.jpg",{exact:true}).waitFor();
    await page.screenshot({path:join(evidence,"01-jpeg-selected.png"),fullPage:true});
    await page.evaluate(()=>{window.dispatchEvent(new Event("offline"));window.dispatchEvent(new Event("online"));});
    assert.equal(await form.locator("textarea").inputValue(),"Synthetic defense test only");
    await form.getByText("sample.jpg",{exact:true}).waitFor();
    await input.setInputFiles({name:"too-big.jpg",mimeType:"image/jpeg",buffer:Buffer.alloc(4_000_001)});
    await form.getByRole("alert").waitFor();
    await page.screenshot({path:join(evidence,"02-oversize-rejected.png"),fullPage:true});
    await form.getByText("sample.jpg",{exact:true}).waitFor();
    await form.getByRole("button",{name:"Submit Document Request"}).click();
    await form.getByText("Synthetic network failure",{exact:false}).waitFor();
    await page.screenshot({path:join(evidence,"03-failure-retains-form.png"),fullPage:true});
    await form.getByText("sample.jpg",{exact:true}).waitFor();
    assert.equal(await form.locator("textarea").inputValue(),"Synthetic defense test only");
    await page.evaluate(()=>{window.fixtureReceipt=true});
    await form.getByRole("button",{name:"Submit Document Request"}).click();
    await page.getByText("TEST-ONLY-001",{exact:true}).waitFor();
    await page.screenshot({path:join(evidence,"04-mocked-receipt.png"),fullPage:true});
    const calls=await page.evaluate(()=>window.fixtureCalls);
    assert.equal(calls.length,2);
    assert.equal(calls[0].id,calls[1].id,"retry must preserve idempotency key");
    assert.equal(calls[1].name,"sample.jpg");
    assert.equal(calls[1].size,jpeg.length);
    console.log("PASS: real Chromium form component: JPEG selection, reconnect, invalid replacement, failure, idempotent retry, receipt (mocked server)");
  } finally { await context.tracing.stop({path:join(evidence,"form-trace.zip")}); await context.close(); }
}
