import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const actions = readFileSync(new URL("../app/(dashboard)/residents/actions.ts", import.meta.url), "utf8");
const client = readFileSync(new URL("../app/(dashboard)/residents/verification/components/VerificationQueueClient.tsx", import.meta.url), "utf8");

test("queue fetch does not sign each ID before rendering the list", () => {
  const queue = actions.split("export async function fetchPendingVerifications")[1].split("export async function fetchResidentIdPhotoUrl")[0];
  assert.ok(queue);
  assert.doesNotMatch(queue, /createSignedUrl/);
  assert.match(queue, /verification_status.*Pending/);
});

test("private ID URLs are generated by permission-checked server action", () => {
  const photo = actions.split("export async function fetchResidentIdPhotoUrl")[1].split("export async function approveResident")[0];
  assert.ok(photo);
  assert.match(photo, /checkUserPermission/);
  assert.match(photo, /createSignedUrl/);
  assert.match(client, /fetchResidentIdPhotoUrl\(selectedResident\.id\)/);
});

test("verification permission checks execute concurrently", () => {
  const queue = actions.split("export async function fetchPendingVerifications")[1].split("export async function fetchResidentIdPhotoUrl")[0];
  assert.match(queue, /Promise\.all\(\[/);
});
